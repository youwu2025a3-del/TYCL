  getMinecraftNews: (options) => invoke('news:list', options),
  translateTexts: (texts, target) => invoke('translate:texts', texts, target),
  getDiagnostics: (instanceId, options) => invoke('diagnostics:get', instanceId, options),
  testNetwork: () => invoke('network:speedtest'),
  minimize: () => invoke('window:minimize'),
  toggleMaximize: () => invoke('window:toggle-maximize'),
  closeWindow: () => invoke('window:close'),
  isMaximized: () => invoke('window:is-maximized'),
  setNativeTheme: (source) => invoke('theme:native', source),
  onTaskProgress: subscribe('task:progress'),
  onTaskDone: subscribe('task:done'),
  onTaskError: subscribe('task:error'),
  onTaskCancelled: subscribe('task:cancelled'),
  onTaskPaused: subscribe('task:paused'),
  onGameStatus: subscribe('game:status'),
  onAccountChanged: subscribe('account:changed'),
