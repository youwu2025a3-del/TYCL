  deleteInstance: (instanceId) => invoke('instances:delete', instanceId),
  getInstanceDetails: (instanceId) => invoke('instances:details', instanceId),
  updateInstanceSettings: (instanceId, patch) => invoke('instances:update-settings', instanceId, patch),
  toggleMod: (instanceId, file, enabled) => invoke('instances:mod-toggle', instanceId, file, enabled),
  deleteMod: (instanceId, file) => invoke('instances:mod-delete', instanceId, file),
  checkModUpdates: (instanceId) => invoke('instances:mod-updates', instanceId),
  backupWorld: (instanceId, worldName) => invoke('instances:backup-world', instanceId, worldName),
  backupInstance: (instanceId) => invoke('instances:backup', instanceId),
