  updateModpack: (instanceId, versionId) => invoke('instances:update-modpack', instanceId, versionId),
  openInstanceFolder: (instanceId) => invoke('instances:open-folder', instanceId),
  cancelTask: (id) => invoke('task:cancel', id),
